
//switch case
//It match the value and based on that it will print the data

let month :number = 0;

switch(month) {
    case 1:
    console.log("jan");
    break;
    
        case 2:
    console.log("feb");
    break;

        case 3:
    console.log("march");
    break;

        case 4:
    console.log("april");
    break;

        case 5:
    console.log("may");
    break;

    default:
        console.log("Invalid month selection");

}